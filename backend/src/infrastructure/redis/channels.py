"""Redis Pub/Sub-каналы об изменении статуса фоновой генерации.

Воркер Celery публикует сюда сообщение, когда тест или рекомендация перешли
в финальный статус, а API (SSE-эндпоинты) подписывается и будит фронт.
Имена каналов собираются только здесь: если бы воркер и API строили строку
каждый сам, опечатка в одном из мест ломала бы уведомления молча —
публикация в канал без подписчиков не считается ошибкой.

Модуль без побочных эффектов при импорте (не создаёт клиентов), поэтому его
безопасно импортировать и из воркера, и из API.

Каналы Pub/Sub глобальны на весь инстанс Redis и не зависят от номера БД
в URL (/0, /1), поэтому имена начинаются с префикса приложения `quiz:`.
"""

from typing import Final

# Сообщение несёт только факт «статус изменился — перечитай». Сам статус
# и данные фронт забирает обычным GET: источник правды один — БД, и
# сериализацию TestOut/AttemptOut не приходится дублировать в воркере.
STATUS_CHANGED_MESSAGE: Final = "changed"


def channel_for_test(test_id: int) -> str:
    """Канал статуса генерации теста."""
    return f"quiz:test:{test_id}"


def channel_for_attempt(attempt_id: int) -> str:
    """Канал статуса генерации рекомендации для попытки."""
    return f"quiz:attempt:{attempt_id}"
